// Текст резервной копии: подготовка к разбору.
//
// Копия — это JSON-файл, но к пользователю он приходит не напрямую: файл пересылают в
// мессенджере, скачивают заново, открывают и сохраняют в редакторах. После такого пути в
// начале текста появляется BOM, а по краям — пробелы и переводы строк. Из-за них
// `JSON.parse` падал с «Unexpected token … is not valid JSON», и по этому сообщению
// невозможно понять, что делать: файл-то был свой, из этого же приложения.
//
// Здесь текст приводится к виду, который `JSON.parse` принимает, и разбирается один раз —
// вместе с понятным сообщением об ошибке. Один и тот же разбор используется и для файла, и
// для копии из облака Telegram, поэтому сообщения совпадают.
//
// Модуль чистый: не читает файлы, не ходит в сеть — его удобно тестировать.

// BOM (U+FEFF) в начале строки: его добавляют «Блокнот» и часть файловых менеджеров.
const LEADING_BOM = /^\uFEFF/

// Убирает BOM и пробелы по краям — всё, что мешает разбору, но не меняет данные.
export function normalizeBackupText(text: string): string {
  return text.replace(LEADING_BOM, '').trim()
}

// Разбирает JSON копии. Сообщение об ошибке написано по-русски: техническое «Unexpected
// token» пользователю ничего не говорит, а причина у разбора всегда одна — файл не JSON.
export function parseBackupJson(text: string): unknown {
  try {
    return JSON.parse(normalizeBackupText(text))
  } catch {
    throw new Error('Файл резервной копии не читается: это не JSON')
  }
}
